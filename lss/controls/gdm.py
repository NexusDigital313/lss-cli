# ---- CIS 1.8.6: Ensure GDM automatic mounting is disabled ----

def _check_gdm_automount() -> CheckResult:
    if not _gdm_installed():
        return CheckResult("pass", "GDM not installed")
    # Check dconf for automount setting
    for conf_path in [
        "/etc/dconf/db/local.d/00-media-automount",
    ]:
        p = Path(conf_path)
        if p.exists():
            try:
                text = p.read_text()
            except OSError:
                continue
            # Require automount=false specifically. The old test ("automount"
            # present AND "false" present anywhere) false-passed on the common
            # `automount=true\nautomount-open=false` pairing — automount itself
            # still enabled.
            if re.search(r"^\s*automount\s*=\s*false", text, re.MULTILINE):
                return CheckResult("pass")

    # Check gsettings if available
    try:
        r = subprocess.run(
            ["gsettings", "get", "org.gnome.desktop.media-handling", "automount"],
            capture_output=True, text=True,
        )
        if r.returncode == 0 and r.stdout.strip() == "false":
            return CheckResult("pass")
    except FileNotFoundError:
        pass

    return CheckResult("warn", "GDM automatic mounting not explicitly disabled")


_GDM_AUTOMOUNT_CONTENT = """[org/gnome/desktop/media-handling]
automount=false
automount-open=false
"""


def _fix_gdm_automount() -> list[RollbackEntry]:
    return [_dconf_write(
        "/etc/dconf/db/local.d/00-media-automount",
        _GDM_AUTOMOUNT_CONTENT,
        "GDM removable-media automount disabled",
    )]


register(Control(
    id="1.8.6",
    title="Ensure GDM automatic mounting of removable media is disabled",
    section="boot",
    check=_check_gdm_automount,
    fix=_fix_gdm_automount,
))


