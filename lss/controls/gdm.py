"""CIS Section 1.8 — GNOME Display Manager (GDM) configuration."""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

from lss.lib import journal
from lss.lib.registry import Control, CheckResult, RollbackEntry, register


def _dconf_write(path: str, content: str, key_human: str) -> RollbackEntry:
    """Write a dconf db fragment and run `dconf update`.

    Raises if the `dconf` binary is missing or `dconf update` fails — the
    keyfile alone is read by LSS's own check but NOT by GDM at runtime.
    GDM reads the compiled binary db at /etc/dconf/db/gdm; that db is only
    regenerated by `dconf update` (provided by the dconf-cli package on
    Debian, dconf on RHEL). Without a successful update, the policy is on
    disk but never enforced — the same cosmetic-pass class that hit 5.3.3
    and 5.3.2.

    Backs up any prior file content; if the file did not exist, rollback
    removes it and re-runs `dconf update` to reconcile the db.
    """
    import shutil as _sh
    if not _sh.which("dconf"):
        raise RuntimeError(
            "dconf binary not found — install dconf-cli (Debian/Ubuntu) or "
            "dconf (RHEL/Fedora) before running GDM hardening fixes. The "
            "keyfile alone does not enforce the policy; the dconf db must "
            "be recompiled."
        )
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    bkp = journal.backup_file(str(p))
    p.write_text(content)
    r = subprocess.run(["dconf", "update"], capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(
            f"dconf update failed (rc={r.returncode}): "
            f"{r.stderr.strip() or r.stdout.strip()}"
        )
    return RollbackEntry(
        action=f"configured {key_human} via {path}",
        path=str(p),
        backup=bkp,
        undo=(
            [["dconf", "update"]]
            if bkp
            else [["rm", "-f", "--", str(p)], ["dconf", "update"]]
        ),
    )


def _gdm_installed() -> bool:
    # If neither package manager is present, GDM cannot have been installed
    # via a package — treat as not installed (mirrors the returncode != 0
    # path) rather than letting FileNotFoundError abort the whole audit.
    try:
        r = subprocess.run(["dpkg-query", "-W", "gdm3"], capture_output=True, text=True)
        if r.returncode == 0 and "install ok installed" in r.stdout:
            return True
    except FileNotFoundError:
        pass
    try:
        r2 = subprocess.run(["rpm", "-q", "gdm"], capture_output=True, text=True)
        return r2.returncode == 0
    except FileNotFoundError:
        return False


# ---- CIS 1.8.1: Ensure GNOME Display Manager is removed (server) ----

def _check_gdm_removed() -> CheckResult:
    if not _gdm_installed():
        return CheckResult("pass", "GDM not installed")
    return CheckResult("warn", "GDM is installed — appropriate for workstation, not server")


register(Control(
    id="1.8.1",
    title="Ensure GDM is removed or login is configured (server profile)",
    section="boot",
    check=_check_gdm_removed,
    fix=None,  # Package removal
))


# ---- CIS 1.8.2: Ensure GDM login banner is configured ----

def _check_gdm_banner() -> CheckResult:
    if not _gdm_installed():
        return CheckResult("pass", "GDM not installed")
    banner_conf = Path("/etc/gdm3/greeter.dconf-defaults")
    if not banner_conf.exists():
        banner_conf = Path("/etc/dconf/db/gdm.d/01-banner-message")
    if banner_conf.exists():
        try:
            text = banner_conf.read_text()
        except OSError:
            text = ""
        if "banner-message-enable" in text and "true" in text.lower():
            return CheckResult("pass")
    return CheckResult("fail", "GDM login banner not configured")


_GDM_BANNER_CONTENT = """[org/gnome/login-screen]
banner-message-enable=true
banner-message-text='Authorized uses only. All activity may be monitored and reported.'
"""


def _fix_gdm_banner() -> list[RollbackEntry]:
    return [_dconf_write(
        "/etc/dconf/db/gdm.d/01-banner-message",
        _GDM_BANNER_CONTENT,
        "GDM login banner",
    )]


register(Control(
    id="1.8.2",
    title="Ensure GDM login banner is configured",
    section="boot",
    check=_check_gdm_banner,
    fix=_fix_gdm_banner,
))


